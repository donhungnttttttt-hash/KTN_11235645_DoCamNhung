const fs=require('node:fs'),{spawnSync}=require('node:child_process');
const {parseConfig,query}=require('../../scripts/database/mysql-client.cjs');
const {testConfiguration}=require('../../scripts/Test-FileWorkQaNative.cjs');
const schema='tms_docstest_202610100016';
const prepared=testConfiguration(parseConfig(fs.readFileSync('.env.mysql.local','utf8')),schema);
if(query('SELECT DATABASE();',prepared.client)[0]!==schema)throw Error('Wrong isolated test database');
if(query('SELECT version FROM flyway_schema_history WHERE success=1 ORDER BY installed_rank DESC LIMIT 1;',prepared.client)[0]!=='29')throw Error('Expected isolated V29');
const selector=process.argv[2]||'NativeExecutionDocumentResultTest';
if(!/^[A-Za-z0-9,*]+$/.test(selector))throw Error('Invalid selector');
const suffix=process.argv[3]||'red';
if(!/^[a-z-]+$/.test(suffix))throw Error('Invalid suffix');
const log=fs.openSync('var/ui-audit/execution-document-'+suffix+'.log','w');
const run=spawnSync('rtk',['proxy','cmd.exe','/d','/c','mvnw.cmd','-B','-ntp','-Dtest='+selector,'verify'],{cwd:'Backend',env:{...process.env,...prepared.environment,TMS_TEST_FQ_MODE:'integration',TMS_TEST_FRESH_MIGRATION:'false'},stdio:['ignore',log,log]});
fs.closeSync(log);
console.log('Isolated '+selector+' exit '+run.status+'; execution-document-'+suffix+'.log');
if(run.error)throw run.error;
process.exitCode=run.status??1;
